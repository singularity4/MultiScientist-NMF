"""
Data sets for the clustering protocol, loaded by the name TASK.md declares.

Two data sets are included. `synthetic` is the data set used in the published
experiments: four clusters in the plane, two with 92 points and two with 8.
`moons` is generated by `_two_moons` below.

Other data sets must be placed in data/ as CSV files with a header row, one point
per row and the label in the last column. After loading, samples are stored as
columns: X is (m x n) for m dimensions and n points.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

DATA_DIR = Path(__file__).resolve().parent.parent / "data"


def load(
    name: str, data_dir: Path | str | None = None
) -> tuple[np.ndarray, np.ndarray, int]:
    """
    Load one data set by name.

    Returns:
        (X, labels_true, n_clusters) — the data matrix (m x n) with samples in
        columns, the ground-truth labels (n,), and the number of clusters.

    Raises:
        FileNotFoundError: if the data set is not present.
    """
    if name == "moons":
        return _two_moons()

    root = Path(data_dir) if data_dir else DATA_DIR

    path = root / f"{name}.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"No {name}.csv in {root}. Only synthetic.csv ships with this "
            "repository; save other data sets as csv with a header, one point per "
            "row, and the label in the last column."
        )

    table = np.loadtxt(path, delimiter=",", skiprows=1)
    X = table[:, :-1].T                      # rows are points in the file, columns here
    labels_true = table[:, -1].astype(int)
    return X, labels_true, int(len(np.unique(labels_true)))


def _two_moons(
    n_per_cluster: int = 100, noise: float = 0.10, seed: int = 0
) -> tuple[np.ndarray, np.ndarray, int]:
    """
    Two interleaved half-circles with 100 points each.

    The first cluster is the upper half of the unit circle, the second that half
    reflected and shifted so the two curve around each other:

        C1 = ( cos t,        sin t )          t ~ U(0, pi)
        C2 = ( 1 - cos t,  0.5 - sin t )

    with isotropic Gaussian noise added to both. Neither cluster is convex, and
    the two clusters are not linearly separable. A factorisation in the input
    space therefore cannot recover them, and the kernel is needed.

    The data are generated from a fixed seed instead of being stored, so the
    arguments of this function fully specify the data set. The noise level sets
    the difficulty.
    """
    rng = np.random.default_rng(seed)
    angles = rng.uniform(0.0, np.pi, n_per_cluster)

    upper = np.vstack([np.cos(angles), np.sin(angles)])
    lower = np.vstack([1.0 - np.cos(angles), 0.5 - np.sin(angles)])
    upper += rng.normal(0.0, noise, upper.shape)
    lower += rng.normal(0.0, noise, lower.shape)

    labels_true = np.repeat([0, 1], n_per_cluster)
    return np.hstack([upper, lower]), labels_true, 2
